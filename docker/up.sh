#!/usr/bin/env bash
# docker/up.sh — bring up the Console. If NEO4J_URI/MORK_URL are set in console.env
# (an external instance), they are used verbatim; otherwise attach to one already
# running on the port, or create a bundled one.
set -euo pipefail

cd "$(dirname "$0")/.."
ENV_FILE="docker/console.env"
COMPOSE_FILE="docker/docker-compose.yml"
COMPOSE=(docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE")

if [ ! -f "$ENV_FILE" ]; then
  echo "✗ Missing $ENV_FILE — copy the example first:" >&2
  echo "    cp docker/console.env.example $ENV_FILE" >&2
  exit 1
fi

set -a; . "$ENV_FILE"; set +a

# An explicit URL in the env (an external instance) wins over everything: used as-is,
# no probing, no bundled service.
ENV_NEO4J_URI="${NEO4J_URI:-}"
ENV_MORK_URL="${MORK_URL:-}"

NEO4J_HOST="${NEO4J_HOST:-}"
NEO4J_BOLT_PORT="${NEO4J_BOLT_PORT:-7687}"
MORK_HOST="${MORK_HOST:-}"
MORK_HOST_PORT="${MORK_HOST_PORT:-8432}"

is_local() {  # blank / loopback counts as "this host"
  case "$1" in ""|localhost|127.0.0.1|0.0.0.0|::1) return 0 ;; *) return 1 ;; esac
}

port_open() {
  timeout 2 bash -c "exec 3<>/dev/tcp/$1/$2" 2>/dev/null
}

port_taken() {
  # Docker refuses to bind a host port any container already maps, so match Docker's view.
  [ -n "$(docker ps --filter "publish=$1" --format '{{.ID}}' 2>/dev/null)" ] && return 0
  port_open 127.0.0.1 "$1"
}

service_running() {
  # Enable both profiles so already-running profiled services are listed (ps filters to active profiles).
  "${COMPOSE[@]}" --profile neo4j --profile mork ps --status running --services 2>/dev/null \
    | grep -qx "$1"
}

# ── Per-species instances ────────────────────────────────────────────────────
# When SPECIES_INSTANCES is set (e.g. "hsa dmel"), provision a Neo4j + MORK per
# species — each on its own host ports and volumes — and tell the Console each
# species' endpoints (NEO4J_URI_<SP>/MORK_URL_<SP>) via a generated override.
# A build for a species then loads into that species' pair, and Explore reads it.
# Internally every Neo4j is on 7687 and every MORK on 8027; only host ports and
# service names differ (neo4j-<sp>, mork-<sp>), so the Console reaches each by
# service name and the same endpoint is used for both load and Explore.
SPECIES_INSTANCES="${SPECIES_INSTANCES:-}"
SPECIES_OVERRIDE="docker/compose.species.yml"
NEO4J_BOLT_BASE="${NEO4J_BOLT_BASE:-7687}"
NEO4J_HTTP_BASE="${NEO4J_HTTP_BASE:-7474}"
MORK_PORT_BASE="${MORK_PORT_BASE:-8432}"

gen_species_override() {
  local out="$1"; shift
  local -a sp_list=("$@")
  local sp UP i=0 bolt http morkp
  {
    echo "# GENERATED by docker/up.sh — per-species Neo4j + MORK instances. Do not edit by hand."
    echo "services:"
    echo "  console:"
    echo "    depends_on:"
    for sp in "${sp_list[@]}"; do echo "      - neo4j-${sp}"; echo "      - mork-${sp}"; done
    echo "    environment:"
    for sp in "${sp_list[@]}"; do
      UP=$(printf '%s' "$sp" | tr '[:lower:]' '[:upper:]')
      echo "      NEO4J_URI_${UP}: bolt://neo4j-${sp}:7687"
      echo "      MORK_URL_${UP}: http://mork-${sp}:8027"
    done
    for sp in "${sp_list[@]}"; do
      bolt=$((NEO4J_BOLT_BASE + i)); http=$((NEO4J_HTTP_BASE + i)); morkp=$((MORK_PORT_BASE + i))
      cat <<YAML
  neo4j-${sp}:
    image: \${NEO4J_IMAGE:-neo4j:5.21}
    ports:
      - "${bolt}:7687"
      - "${http}:7474"
    environment:
      NEO4J_AUTH: "\${NEO4J_USER:-neo4j}/\${NEO4J_PASSWORD:?set NEO4J_PASSWORD in docker/console.env}"
      NEO4JLABS_PLUGINS: '["apoc"]'
      NEO4J_apoc_export_file_enabled: "true"
      NEO4J_apoc_import_file_enabled: "true"
      NEO4J_apoc_import_file_use__neo4j__config: "false"
      NEO4J_dbms_security_procedures_unrestricted: "apoc.*"
      NEO4J_dbms_security_allow__csv__import__from__file__urls: "true"
      NEO4J_server_directories_import: "/"
      NEO4J_server_memory_pagecache_size: "\${NEO4J_PAGECACHE:-1G}"
      NEO4J_server_memory_heap_max__size: "\${NEO4J_HEAP_MAX:-1G}"
    volumes:
      - "\${DATA_ROOT}:\${DATA_ROOT}:ro"
      - neo4j_data_${sp}:/data
      - neo4j_logs_${sp}:/logs
  mork-${sp}:
    build:
      context: ../biocypher-mork
    ports:
      - "${morkp}:8027"
    volumes:
      - "\${DATA_ROOT}:\${DATA_ROOT}"
      - mork_persist_${sp}:/app/persist
YAML
      i=$((i + 1))
    done
    echo "volumes:"
    for sp in "${sp_list[@]}"; do
      echo "  neo4j_data_${sp}: {}"
      echo "  neo4j_logs_${sp}: {}"
      echo "  mork_persist_${sp}: {}"
    done
  } >"$out"
}

if [ -n "$SPECIES_INSTANCES" ]; then
  read -ra SP_ARR <<<"$SPECIES_INSTANCES"
  gen_species_override "$SPECIES_OVERRIDE" "${SP_ARR[@]}"
  first="${SP_ARR[0]}"
  # Global default points at the first species so observatory/default code stays valid.
  export NEO4J_URI="bolt://neo4j-${first}:7687"
  export MORK_URL="http://mork-${first}:8027"
  echo
  echo "─────────────────────────────────────────────"
  echo "  per-species instances: ${SPECIES_INSTANCES}"
  echo "  wrote ${SPECIES_OVERRIDE}"
  echo "  default NEO4J_URI = ${NEO4J_URI}"
  echo "─────────────────────────────────────────────"
  echo
  exec "${COMPOSE[@]}" -f "$SPECIES_OVERRIDE" up -d --build --remove-orphans "$@"
fi

PROFILES=()

# ── Neo4j ────────────────────────────────────────────────────────────────────
if [ -n "$ENV_NEO4J_URI" ]; then
  echo "→ Neo4j: using NEO4J_URI from ${ENV_FILE} (${ENV_NEO4J_URI})"
  export NEO4J_URI="$ENV_NEO4J_URI"
elif service_running neo4j; then
  echo "✔ Neo4j: reusing the bundled service already running"
  PROFILES+=(--profile neo4j)
  export NEO4J_URI="bolt://neo4j:7687"
elif ! is_local "$NEO4J_HOST"; then
  echo "→ Neo4j: attaching to remote ${NEO4J_HOST}:${NEO4J_BOLT_PORT}"
  port_open "$NEO4J_HOST" "$NEO4J_BOLT_PORT" \
    || { echo "✗ Neo4j unreachable at ${NEO4J_HOST}:${NEO4J_BOLT_PORT} (can't create it remotely)"; exit 1; }
  export NEO4J_URI="bolt://${NEO4J_HOST}:${NEO4J_BOLT_PORT}"
elif port_taken "$NEO4J_BOLT_PORT"; then
  owner=$(docker ps --filter "publish=$NEO4J_BOLT_PORT" --format '{{.Names}}' 2>/dev/null | head -1)
  echo "✔ Neo4j: attaching to existing instance on localhost:${NEO4J_BOLT_PORT}${owner:+ (container: $owner)}"
  export NEO4J_URI="bolt://host.docker.internal:${NEO4J_BOLT_PORT}"
else
  echo "＋ Neo4j: none found on :${NEO4J_BOLT_PORT} — creating the bundled service"
  PROFILES+=(--profile neo4j)
  export NEO4J_URI="bolt://neo4j:7687"
fi

# ── MORK ─────────────────────────────────────────────────────────────────────
if [ -n "$ENV_MORK_URL" ]; then
  echo "→ MORK: using MORK_URL from ${ENV_FILE} (${ENV_MORK_URL})"
  export MORK_URL="$ENV_MORK_URL"
elif service_running mork; then
  echo "✔ MORK: reusing the bundled service already running"
  PROFILES+=(--profile mork)
  export MORK_URL="http://mork:8027"
elif ! is_local "$MORK_HOST"; then
  echo "→ MORK: attaching to remote ${MORK_HOST}:${MORK_HOST_PORT}"
  port_open "$MORK_HOST" "$MORK_HOST_PORT" \
    || { echo "✗ MORK unreachable at ${MORK_HOST}:${MORK_HOST_PORT} (can't create it remotely)"; exit 1; }
  export MORK_URL="http://${MORK_HOST}:${MORK_HOST_PORT}"
elif port_taken "$MORK_HOST_PORT"; then
  owner=$(docker ps --filter "publish=$MORK_HOST_PORT" --format '{{.Names}}' 2>/dev/null | head -1)
  echo "✔ MORK: attaching to existing instance on localhost:${MORK_HOST_PORT}${owner:+ (container: $owner)}"
  export MORK_URL="http://host.docker.internal:${MORK_HOST_PORT}"
else
  echo "＋ MORK: none found on :${MORK_HOST_PORT} — creating the bundled service"
  PROFILES+=(--profile mork)
  export MORK_URL="http://mork:8027"
fi

echo
echo "─────────────────────────────────────────────"
echo "  NEO4J_URI = ${NEO4J_URI}"
echo "  MORK_URL  = ${MORK_URL}"
echo "  profiles  = ${PROFILES[*]:-<console only>}"
echo "─────────────────────────────────────────────"
echo

# --remove-orphans is scoped to this project, so it never touches foreign stacks.
exec "${COMPOSE[@]}" "${PROFILES[@]}" up -d --build --remove-orphans "$@"
